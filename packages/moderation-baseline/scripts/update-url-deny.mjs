#!/usr/bin/env node

import { readFile, rename, writeFile } from "node:fs/promises";
import { request } from "node:https";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "dict", "url_deny.toml");
const ALLOW = join(ROOT, "dict", "url_allow.toml");
const MAX_RESPONSE_BYTES = 16 * 1024 * 1024;
const ENTRIES_PER_SOURCE = 512;
const SOURCES = [
  {
    category: "ransomware-host",
    url: "https://raw.githubusercontent.com/blocklistproject/Lists/master/alt-version/ransomware-nl.txt",
  },
  {
    category: "scam-host",
    url: "https://raw.githubusercontent.com/blocklistproject/Lists/master/alt-version/scam-nl.txt",
  },
];

function download(url, redirects = 0) {
  if (redirects > 3) throw new Error(`too many redirects while fetching ${url}`);
  return new Promise((resolve, reject) => {
    const req = request(url, {
      headers: { "user-agent": "arinova-moderation-baseline-updater/1.0" },
    });
    req.setTimeout(30_000, () => req.destroy(new Error(`timed out fetching ${url}`)));
    req.on("response", (response) => {
      if (response.statusCode >= 300 && response.statusCode < 400 && response.headers.location) {
        response.resume();
        resolve(download(new URL(response.headers.location, url).href, redirects + 1));
        return;
      }
      if (response.statusCode !== 200) {
        response.resume();
        reject(new Error(`fetch ${url} returned HTTP ${response.statusCode}`));
        return;
      }
      const chunks = [];
      let size = 0;
      response.on("data", (chunk) => {
        size += chunk.length;
        if (size > MAX_RESPONSE_BYTES) {
          response.destroy(new Error(`fetch ${url} exceeded ${MAX_RESPONSE_BYTES} bytes`));
          return;
        }
        chunks.push(chunk);
      });
      response.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
      response.on("error", reject);
    });
    req.on("error", reject);
    req.end();
  });
}

function validDomain(value) {
  if (value.length > 253 || !value.includes(".") || value.includes("..")) return false;
  return value.split(".").every(
    (label) =>
      label.length > 0 &&
      label.length <= 63 &&
      /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(label),
  );
}

function domainsFromFeed(body) {
  return body
    .split(/\r?\n/)
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line && !line.startsWith("#") && validDomain(line));
}

function isAllowlisted(domain, allowlisted) {
  return allowlisted.some(
    (allowed) => domain === allowed || domain.endsWith(`.${allowed}`),
  );
}

function render(entries) {
  const today = new Date().toISOString().slice(0, 10);
  const lines = [
    "[meta]",
    'list_name      = "url_deny"',
    'version        = "0.1.0-seed"',
    `last_updated   = ${JSON.stringify(today)}`,
    'maintained_by  = "Ripple Company / generated by scripts/update-url-deny.mjs"',
    'review_cadence = "daily"',
    "source_refs    = [",
    ...SOURCES.map(({ url }) => `  ${JSON.stringify(url)},`),
    "]",
    "",
    "# Generated deterministically from the source feeds above.",
    "# Do not hand-edit entries; update the source configuration and rerun the updater.",
  ];
  for (const entry of entries) {
    lines.push(
      "",
      "[[entries]]",
      `domain   = ${JSON.stringify(entry.domain)}`,
      `category = ${JSON.stringify(entry.category)}`,
      'severity = "block"',
      'applies  = ["web_search.output"]',
      `audit    = ${JSON.stringify(`source=${entry.url}`)}`,
    );
  }
  return `${lines.join("\n")}\n`;
}

const allowBody = await readFile(ALLOW, "utf8");
const allowlisted = [...allowBody.matchAll(/^\s*domain\s*=\s*"([^"]+)"\s*$/gm)]
  .map((match) => match[1].toLowerCase());
const selected = [];
const seen = new Set();

for (const source of SOURCES) {
  const body = await download(source.url);
  let sourceCount = 0;
  for (const domain of domainsFromFeed(body)) {
    if (seen.has(domain) || isAllowlisted(domain, allowlisted)) continue;
    selected.push({ domain, category: source.category, url: source.url });
    seen.add(domain);
    sourceCount += 1;
    if (sourceCount === ENTRIES_PER_SOURCE) break;
  }
  if (sourceCount !== ENTRIES_PER_SOURCE) {
    throw new Error(
      `${source.url} yielded ${sourceCount} safe domains; expected ${ENTRIES_PER_SOURCE}`,
    );
  }
}

selected.sort((left, right) => left.domain.localeCompare(right.domain));
const temporary = `${OUTPUT}.tmp-${process.pid}`;
await writeFile(temporary, render(selected), { encoding: "utf8", mode: 0o644 });
await rename(temporary, OUTPUT);
console.log(`updated ${OUTPUT} with ${selected.length} deny entries`);
